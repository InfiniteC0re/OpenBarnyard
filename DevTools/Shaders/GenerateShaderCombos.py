#!/usr/bin/env python3
"""Generates the combo header of .hlsl files for Toshi::TShaderCombo (Toshi/Source/Platform/DX11/TShaderCombo_DX11.h).

The combos are declared at the top of the shader, before any code:
    // STATIC: "FOG" "0..1" [ps]
    // STATIC: "LIGHTS" "0..3"
The optional [vs] / [ps] / [cs] tag says which stage the combo affects, untagged combos affect all of them.

    python GenerateShaderCombos.py <shader.hlsl>... --out-dir <dir>

writes <Name>ShaderCombos.h for each shader with a struct <Name>ShaderCombos holding the definition
table and a helper per combo; the permutation index is the sum of the helpers:
    GrassShaderCombos::FOG( bFog ) + GrassShaderCombos::LIGHTS( iNumLights )
TShaderCombo::Create checks the table against the shader, so a stale header asserts at startup.
"""
import argparse
import re
import sys
from pathlib import Path

COMBO_RE = re.compile( r'^\s*//\s*STATIC:\s*"([^"]+)"\s*"(-?\d+)\.\.(-?\d+)"(?:\s*\[(vs|ps|cs)\])?' )
STAGES   = { None: "STAGE_ALL", "vs": "STAGE_VS", "ps": "STAGE_PS", "cs": "STAGE_CS" }


def parse_combos( path ):
	combos = []

	for line in path.read_text( encoding = "utf-8" ).splitlines():
		stripped = line.strip()

		# The declarations end at the first line of code
		if stripped and not stripped.startswith( "//" ):
			break

		match = COMBO_RE.match( line )
		if not match:
			continue

		name, min_value, max_value, stage = match.groups()
		min_value, max_value = int( min_value ), int( max_value )

		if not re.fullmatch( r"[A-Za-z_][A-Za-z0-9_]*", name ):
			sys.exit( f"{path}: combo name '{name}' isn't a valid identifier" )
		if min_value > max_value:
			sys.exit( f"{path}: combo {name} has an empty range" )
		if any( c[ 0 ] == name for c in combos ):
			sys.exit( f"{path}: combo {name} is declared twice" )

		combos.append( ( name, min_value, max_value, stage ) )

	return combos


def generate( path, out_dir ):
	name   = re.sub( r"[^A-Za-z0-9_]", "_", path.stem )
	combos = parse_combos( path )

	stride  = 1
	entries = []
	for combo, min_value, max_value, stage in combos:
		entries.append( ( combo, min_value, max_value, stride, stage ) )
		stride *= max_value - min_value + 1

	if stride > 0xFFFF:
		sys.exit( f"{path}: {stride} permutations, TShaderCombo supports up to 65535" )

	out = [
		"#pragma once",
		f"// Generated by DevTools/Shaders/GenerateShaderCombos.py from {path.name}, do not edit",
		"#include <Platform/DX11/TShaderCombo_DX11.h>",
		"",
		f"struct {name}ShaderCombos",
		"{",
	]

	if entries:
		out.append( "\tstatic constexpr Toshi::TShaderCombo::Definition s_aCombos[] = {" )
		for combo, min_value, max_value, combo_stride, stage in entries:
			out.append( f'\t\t{{ "{combo}", {min_value}, {max_value}, {combo_stride}, Toshi::TShaderCombo::{STAGES[ stage ]} }},' )
		out.append( "\t};" )
	else:
		out.append( "\tstatic constexpr const Toshi::TShaderCombo::Definition* s_aCombos = TNULL;" )

	out.append( "" )
	out.append( f"\tstatic constexpr TUINT NUM_COMBOS       = {len( entries )};" )
	out.append( f"\tstatic constexpr TUINT NUM_PERMUTATIONS = {stride};" )

	for combo, min_value, max_value, combo_stride, stage in entries:
		offset = f"a_iValue - {min_value}" if min_value > 0 else f"a_iValue + {-min_value}" if min_value < 0 else "a_iValue"
		out.append( "" )
		out.append( f"\t// {min_value}..{max_value}" + ( f", {stage.upper()} only" if stage else "" ) )
		out.append( f"\tstatic constexpr TUINT {combo}( TINT a_iValue ) {{ return TUINT( {offset} ) * {combo_stride}; }}" )

	out.append( "};" )
	out.append( "" )

	out_dir.mkdir( parents = True, exist_ok = True )
	out_path = out_dir / f"{name}ShaderCombos.h"
	out_path.write_text( "\n".join( out ), encoding = "utf-8" )
	return out_path


def main():
	parser = argparse.ArgumentParser( description = "Generates TShaderCombo headers from the combo declarations of .hlsl files." )
	parser.add_argument( "shaders", nargs = "+", type = Path )
	parser.add_argument( "--out-dir", type = Path, required = True )
	args = parser.parse_args()

	for shader in args.shaders:
		print( generate( shader.resolve(), args.out_dir.resolve() ) )


if __name__ == "__main__":
	main()
