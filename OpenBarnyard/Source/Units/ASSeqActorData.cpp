// $Barnyard: FUNCTION 00629c60
// $BarnyardWiiJP: FUNCTION 803da068
TINT ASSeqActorData::FindActorIndex( const TCHAR* a_szName )
{
	for ( TINT i = 0; i < NUM_ACTORS; i++ )
	{
		if ( TStringManager::String8CompareNoCase( a_szName, ms_aActorNames[ i ] ) == 0 )
			return i;
	}

	return -1;
}

// $Barnyard: FUNCTION 00628fb0
TBOOL ASSeqActorData::Create( const PBProperties* a_pProperties )
{
	TPString8 strActorName;
	a_pProperties->GetOptionalPropertyValue( strActorName, TPS8( ActorName ) );

	m_iActorIndex = FindActorIndex( strActorName.GetString() );

	return TTRUE;
}
