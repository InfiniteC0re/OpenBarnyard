// $Barnyard: FUNCTION 00563e90
TBOOL AInteriorSteer::SeekPoint( const TVector4& a_rcPoint )
{
	if ( IsFollowingPath() )
		Command_CancelCurrentCommandNoStop();

	AInteriorNetwork* pNetwork = GetNetwork();

	if ( pNetwork && !IsFollowingPath() && pNetwork->BuildPathToContainingArea( &m_oPath, a_rcPoint ) )
	{
		StartFollowingPath();
		return TTRUE;
	}

	// Move the point towards the closest area until a path to it is found
	TINT     iArea = GetNetwork()->FindClosestArea( a_rcPoint );
	TVector4 vecAreaPos;
	GetNetwork()->m_pINetwork->m_pAreas[ iArea ].GetPosition( vecAreaPos );

	TVector4 vecDir;
	vecDir.x = a_rcPoint.x - vecAreaPos.x;
	vecDir.y = a_rcPoint.y - vecAreaPos.y;
	vecDir.z = a_rcPoint.z - vecAreaPos.z;
	vecDir.w = a_rcPoint.w;

	TFLOAT fDistance = vecDir.NormaliseMag();

	if ( fDistance >= 5.0f )
		return TFALSE;

	for ( TINT i = 5;; i-- )
	{
		TVector4 vecOffset;
		vecOffset.Multiply( vecDir, fDistance );
		vecOffset.Multiply( TFLOAT( i ) * ( 1.0f / 6.0f ) );

		TVector4 vecPoint( vecOffset.x + vecAreaPos.x, vecOffset.y + vecAreaPos.y, vecOffset.z + vecAreaPos.z, vecAreaPos.w );

		pNetwork = GetNetwork();

		if ( pNetwork && !IsFollowingPath() && pNetwork->BuildPathToContainingArea( &m_oPath, vecPoint ) )
		{
			StartFollowingPath();
			return TTRUE;
		}

		// NOTE: retail returns TTRUE even though no path was found
		if ( i == 0 )
			return TTRUE;
	}
}

// $Barnyard: FUNCTION 00564260
TBOOL AInteriorSteer::PatrolPoint( const TVector4& a_rcPoint, TFLOAT a_fDistance, TFLOAT a_fAngle )
{
	TVector4 vecPosition = *GetPosition();

	// Rotate the direction from the point to the unit by a fifth of a half turn per a_fAngle unit
	TVector4 vecDir = vecPosition;
	vecDir.Substract( a_rcPoint );
	vecDir.Normalise();
	vecDir.AsVector3().RotateY( a_fAngle * TMath::PI * 0.2f );
	vecDir.Multiply( a_fDistance );

	TVector4 vecPatrolPoint = vecDir;
	vecPatrolPoint.Add( a_rcPoint );
	vecPatrolPoint.w = a_rcPoint.w;

	// Only go 2 units towards it
	TVector4 vecToPoint = vecPatrolPoint;
	vecToPoint.Substract( vecPosition );
	vecToPoint.Normalise();

	TVector4 vecTarget;
	vecTarget.Multiply( vecToPoint, 2.0f );
	vecTarget.Add( vecPosition );
	vecTarget.w = vecPosition.w;

	if ( IsFollowingPath() )
		Command_CancelCurrentCommandNoStop();

	AInteriorNetwork* pNetwork = GetNetwork();

	if ( pNetwork && !IsFollowingPath() && pNetwork->BuildPathToContainingArea( &m_oPath, vecTarget ) )
	{
		StartFollowingPath();
		return TTRUE;
	}

	return SeekPoint( a_rcPoint );
}

