// $Barnyard: FUNCTION 00564b70
void AInteriorSteer::UpdatePathFollowing( TFLOAT a_fDeltaTime, AInteriorNetwork* a_pNetwork, TBOOL* a_pRepath, TBOOL* a_pUnk )
{
	m_fRepathTime -= a_fDeltaTime;

	if ( m_fRepathTime <= 0.0f )
	{
		m_fRepathTime = 20.0f;
		*a_pRepath    = TTRUE;
	}

	TBOOL bStopped = TFALSE;

	if ( m_eFlags & FLAGS_SEEKING_PATH_END )
	{
		// Stop once the unit stands in the last area of the path
		if ( m_oPath.m_iStartArea == m_oPath.m_oPath.GetPathAreaIndex( m_oPath.m_oPath.m_iNumPathAreas - 1 ) &&
		     a_pNetwork->IsInsideStartArea( &m_oPath, m_oPath.m_vStartPosition, TFALSE, 2.0f ) )
		{
			*a_pRepath = TFALSE;
			m_eFlags &= ~FLAGS_SEEKING_PATH_END;
			StopFollowingPath( a_pNetwork );
			bStopped = TTRUE;
		}
	}
	else if ( m_eFlags & FLAGS_OFF_NETWORK )
	{
		// Stop once the unit is back on the network
		if ( a_pNetwork->IsInsideStartArea( &m_oPath, m_oPath.m_vStartPosition, TFALSE, 2.0f ) )
		{
			*a_pRepath = TFALSE;
			m_eFlags &= ~FLAGS_OFF_NETWORK;
			StopFollowingPath( a_pNetwork );
			bStopped = TTRUE;
		}
	}

	if ( !bStopped )
	{
		if ( m_pKinematics->IsSeekingConstant() )
		{
			// Still walking to the next point, repath if a special area is coming
			*a_pRepath = a_pNetwork->FindSpecialAreaInPath( &m_oPath.m_oPath, 10 );
		}
		else if ( m_oPath.m_oPath.ReachedDestination() )
		{
			if ( m_oPath.m_oPath.m_iGoalIndex == -1 )
			{
				StopFollowingPath( a_pNetwork );
				*a_pRepath = TFALSE;
			}
			else
			{
				OnReachedPathEnd( a_pNetwork, a_pRepath, a_pUnk );
			}
		}
		else
		{
			// Reached the next point, get the one after it
			*a_pRepath = TTRUE;
		}
	}

	if ( TSTATICCAST( ASteerKinematics2D, m_pKinematics )->GetFlags() & ASteerKinematics2D::FLAGS_CHECK_BLOCKED )
		UpdateObstruction( a_fDeltaTime );
}

// $Barnyard: FUNCTION 00563220
void AInteriorSteer::OnReachedPathEnd( AInteriorNetwork* a_pNetwork, TBOOL* a_pRepath, TBOOL* a_pUnk )
{
	m_eFlags &= ~FLAGS_OFF_NETWORK;
	m_eFlags &= ~FLAGS_SEEKING_PATH_END;

	if ( m_oPath.m_oPath.m_vForward.MagnitudeSq() > 0.0f )
	{
		m_pKinematics->SetSpeed( 0.0f );

		TVector4 vecDestination = m_oPath.m_oPath.m_vDestination;
		m_pKinematics->SetPosition( vecDestination );

		AModelInstance* pModel = TSTATICCAST( AVisibleUnit, &GetParentUnit() )->GetModelInstance();
		pModel->GetTransform().SetTranslate( m_pKinematics->GetPosition()->AsVector3() );
		pModel->UpdateLighting();
	}

	if ( m_oPath.m_oPath.ReachedDestination() )
	{
		if ( !GetParentUnit().HasInteraction() )
			*a_pUnk = TTRUE;

		*a_pRepath = TFALSE;
	}
	else
	{
		*a_pRepath = TTRUE;
	}
}

// Whether a character other than a_pIgnore stands within a_fRadius of the segment a_pStart-a_pEnd.
// $Barnyard: FUNCTION 00561bd0
static TBOOL __stdcall IsSegmentBlockedByCharacter( AUnitHash::QueryResult* a_pUnits, TUINT a_uiNumUnits, const TVector4* a_pStart, const TVector4* a_pEnd, AUnit* a_pIgnore, TFLOAT a_fRadius )
{
	TFLOAT fRadiusSq = a_fRadius * a_fRadius;

	for ( TUINT i = 0; i < a_uiNumUnits; i++ )
	{
		AUnit* pUnit = a_pUnits[ i ].pUnit;

		if ( pUnit != a_pIgnore && pUnit->IsA( &TGetClass( ACharacterUnit ) ) )
		{
			TVector4 vecPosition;
			pUnit->GetSteer()->CopyPosition( vecPosition );

			TFLOAT fT; // NOTE: retail reuses the stack slot of a_pIgnore
			if ( TMath::DistancePointToSegmentSq( vecPosition, *a_pStart, *a_pEnd, fT ) < fRadiusSq )
				return TTRUE;
		}
	}

	return TFALSE;
}

// 0x00788dd0
static AInteriorNetworkPath::BuildPathState s_oSideStepPath;

// $Barnyard: FUNCTION 005637f0
void AInteriorSteer::UpdateObstruction( TFLOAT a_fDeltaTime )
{
	AInteriorNetwork* pNetwork = GetNetwork();

	if ( !pNetwork )
		return;

	ASteerKinematics2D* pKinematics = TSTATICCAST( ASteerKinematics2D, m_pKinematics );

	if ( m_oPath.m_oPath.m_uiFlags & AInteriorNetworkPath::BuildPathState::FLAGS_SIDE_STEP )
	{
		// Side stepping, go back to the path once there (or after a while)
		TFLOAT fDistanceSq = TVector4::DistanceSq( m_oPath.m_oPath.m_vSideStepTarget, *pKinematics->GetPosition() );

		if ( m_pKinematics->GetSpeed() > 0.0f )
			m_fObstructionTime -= a_fDeltaTime;

		if ( m_fObstructionTime <= 0.0f || fDistanceSq < 1.0f )
		{
			m_oPath.m_oPath.m_uiFlags &= ~AInteriorNetworkPath::BuildPathState::FLAGS_SIDE_STEP;
			m_fObstructionTime = 0.0f;
			pKinematics->ResetAvoiding();
			StartFollowingPath();
		}
	}
	else if ( pKinematics->IsAvoiding() )
	{
		// Something blocks the way, try to side step it once a second
		TScheduler* pScheduler = g_oSystemManager.GetScheduler();

		if ( pScheduler->GetTotalTime() - m_fObstructionTime < 1.0f )
			return;

		m_fObstructionTime = pScheduler->GetTotalTime();

		const TVector4*         pPosition = GetPosition();
		TINT                    iNumUnits;
		AUnitHash::QueryResult* pUnits = AUnitManager::GetSingleton()->FindUnits( *pPosition, 4.0f, &iNumUnits, TFALSE, 20, TFALSE, TNULL );

		// To the left and to the right of the facing
		TVector4 vecSide;
		vecSide.CrossProduct( *pKinematics->GetDesiredFacing(), TVector4::VEC_NEGY );
		vecSide.Multiply( 2.5f );

		TFLOAT afSides[ 2 ] = { 1.0f, -1.0f };

		for ( TINT i = 0; i < 2; i++ )
		{
			vecSide.Multiply( afSides[ i ] );

			TVector4 vecTarget( vecSide.x + pPosition->x, vecSide.y + pPosition->y, vecSide.z + pPosition->z, vecSide.w );
			TINT     iArea = pNetwork->FindAreaFittingCircle( vecTarget, GetRadius(), m_oPath.m_iStartArea );

			// NOTE: retail checks the result of the previous side here, it's always TFALSE at this point
			if ( iArea < 0 )
				continue;

			if ( m_oPath.m_iStartArea != iArea )
			{
				// The area has to be reachable
				s_oSideStepPath.Reset();

				if ( !pNetwork->BuildPathToArea( m_oPath.m_iStartArea, iArea, &s_oSideStepPath ) )
					continue;
			}

			if ( !IsSegmentBlockedByCharacter( pUnits, iNumUnits, pPosition, &vecTarget, &GetParentUnit(), 0.4f ) )
			{
				m_oPath.m_oPath.SetSideStepTarget( vecTarget );
				StartFollowingPath();
				m_fObstructionTime = 3.0f;
				return;
			}
		}
	}
}

