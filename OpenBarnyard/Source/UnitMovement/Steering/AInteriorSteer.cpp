// $Barnyard: FUNCTION 005659f0
void AInteriorSteer::AttachToLocator( const TCHAR* a_szLocator )
{
	AAnimatedUnit* pUnit = TSTATICCAST( AAnimatedUnit, &GetParentUnit() );

	if ( pUnit->GetAnimatableObject()->GetLocator() )
		RemoveFromLocator(); // NOTE: inlined in retail

	pUnit->GetAnimatableObject()->AttachToLocator( a_szLocator );

	TVector4    vecPosition;
	TQuaternion quatRotation;
	ATerrainInterface::GetSingleton()->GetLocatorPosAndRot( a_szLocator, vecPosition, quatRotation );

	AInteriorNetwork* pNetwork = GetNetwork();

	if ( pNetwork )
	{
		TINT iArea = pNetwork->FindContainingArea( vecPosition );

		if ( iArea >= 0 )
			SnapToArea( iArea );
	}

	SetInteracting( 1 );
	Halt();
	HaltAtPosition( vecPosition.AsVector3() );

	// NOTE: retail faces along the x/z part of the locator's rotation quaternion
	TVector4 vecFacing( quatRotation.x, 0.0f, quatRotation.z, quatRotation.w );
	vecFacing.Normalise();
	HaltFacing( vecFacing.AsVector3() );

	m_iUnk500 = 0;
	m_eMode   = MODE_STILL;

	// NOTE: inlined in retail
	UpdateModelTransform();
}

