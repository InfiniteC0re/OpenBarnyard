// $Barnyard: FUNCTION 00565380
TBOOL AInteriorSteer::UpdateSeekUnit()
{
	AInteriorNetwork* pNetwork = GetNetwork();
	m_pKinematics->Halt();

	if ( pNetwork )
	{
		pNetwork->ResetPath( &m_oPath );

		AUnit* pTarget = m_oTargetUnit.Get() ? m_oTargetUnit->GetUnit() : TNULL;

		if ( pTarget )
		{
			TVector4 vecTargetPos;
			TVector4 vecPosition;
			TVector4 vecTargetDir;

			pTarget->GetSteer()->CopyPosition( vecTargetPos );
			CopyPosition( vecPosition );
			pTarget->GetSteer()->CopyDirection( vecTargetDir );

			// Seek the point in front of the target, just outside of both units
			vecTargetDir.Multiply( -1.0f );
			vecTargetDir.Multiply( pTarget->GetSteer()->GetRadius() + GetRadius() );

			TVector4 vecGoal = vecTargetPos + vecTargetDir;

			TVector4 vecToGoal = vecGoal - vecPosition;
			vecToGoal.Normalise();

			TVector4 vecOffset;
			vecOffset.Multiply( vecToGoal, m_fTargetDistance );

			TVector4 vecTarget = vecGoal - vecOffset;

			if ( pNetwork->BuildPathToContainingArea( &m_oPath, vecTarget ) )
			{
				StartFollowingPath();
				return TTRUE;
			}

			pNetwork->ResetPath( &m_oPath );
		}
	}

	m_oTargetUnit = TNULL;
	m_eFlags &= ~FLAGS_SEEKING_UNIT;

	return TFALSE;
}

// $Barnyard: FUNCTION 00565520
TBOOL AInteriorSteer::UpdateAvoidUnit()
{
	AInteriorNetwork* pNetwork = GetNetwork();
	m_pKinematics->Halt();

	if ( pNetwork )
	{
		pNetwork->ResetPath( &m_oPath );

		AUnit* pTarget = m_oTargetUnit.Get() ? m_oTargetUnit->GetUnit() : TNULL;

		if ( pTarget )
		{
			TVector4 vecTargetPos;
			pTarget->GetSteer()->CopyPosition( vecTargetPos );

			// Direction away from the target on the XZ plane
			TVector4 vecAway = *GetPosition();
			vecAway.x -= vecTargetPos.x;
			vecAway.y = 0.0f;
			vecAway.z -= vecTargetPos.z;

			TFLOAT fDistanceSq = vecAway.MagnitudeSq(); // 006c74d0

			if ( fDistanceSq < m_fTargetDistance * m_fTargetDistance )
			{
				if ( fDistanceSq < 1.1920929e-07f ) // FLT_EPSILON
				{
					// Right on top of it, pick a random direction
					vecAway = TVector4::VEC_POSZ;
					vecAway.AsVector3().RotateY( ARandom::GetSingleton()->m_oRandom.GetFloatMinMax( 0.0f, TMath::TWO_PI ) );
				}
				else
				{
					vecAway.Multiply( 1.0f / TMath::Sqrt( fDistanceSq ) );
				}

				TVector4 vecTarget = vecAway;
				vecTarget.Multiply( m_fTargetDistance );

				// NOTE: vecTarget is an offset, not a point (retail bug)
				if ( pNetwork->BuildPathToContainingArea( &m_oPath, vecTarget ) )
				{
					StartFollowingPath();
					return TTRUE;
				}

				TVector4 vecFound;

				if ( pNetwork->FindPointAwayFrom( *GetPosition(), m_fTargetDistance, vecAway, 0.0f, vecFound, m_bAvoidUnk, 5 ) )
				{
					pNetwork->ResetPath( &m_oPath );

					if ( pNetwork->BuildPathToContainingArea( &m_oPath, vecFound ) )
					{
						StartFollowingPath();
						return TTRUE;
					}
				}

				TINT iArea = pNetwork->FindClosestArea( vecTarget );

				if ( iArea >= 0 )
				{
					pNetwork->m_pINetwork->m_pAreas[ iArea ].GetPositionXZ( vecFound );
					pNetwork->ResetPath( &m_oPath );

					if ( pNetwork->BuildPathToContainingArea( &m_oPath, vecFound ) )
					{
						StartFollowingPath();
						return TTRUE;
					}
				}
			}

			pNetwork->ResetPath( &m_oPath );
		}
	}

	m_oTargetUnit = TNULL;
	m_eFlags &= ~FLAGS_AVOIDING_UNIT;

	return TFALSE;
}

