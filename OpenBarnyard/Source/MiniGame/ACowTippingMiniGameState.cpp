// Gets the transforms of the hens (the hen locators of the instances of model 128) of the junkyard stages
// $Barnyard: FUNCTION 004aaf30
void ACowTippingMiniGameState::FindHenTransforms()
{
	if ( !IsJunkyardStage( m_aStages[ m_iStage ].iStageType ) )
		return;

	constexpr TUINT8 HEN_MODEL_INDEX = 128;

	AInstanceManager* pInstanceManager = AInstanceManager::GetSingleton();
	TSkeleton*        pSkeleton        = pInstanceManager->GetModel( HEN_MODEL_INDEX )->pManagedModel->GetModel()->GetSkeleton();

	TINT aBones[ 3 ];
	aBones[ 0 ] = pSkeleton->GetBoneID( "hen1_loc", 0 );
	aBones[ 1 ] = pSkeleton->GetBoneID( "hen2_loc", 0 );
	aBones[ 2 ] = pSkeleton->GetBoneID( "hen3_loc", 0 );

	TINT iNumHens = 0;

	for ( TINT i = 0;; i++ )
	{
		AInstanceManager::StaticInstanceEntry* pInstance = pInstanceManager->FindInstance( HEN_MODEL_INDEX, i );

		if ( !pInstance )
			break;

		iNumHens += TARRAYSIZE( aBones );

		for ( TINT k = 0; k < TARRAYSIZE( aBones ); k++ )
			pInstanceManager->GetInstanceBoneTransform( HEN_MODEL_INDEX, pInstance, aBones[ k ], m_aHenTransforms[ i * TARRAYSIZE( aBones ) + k ] );
	}

	m_iNumHens = iNumHens;
}

