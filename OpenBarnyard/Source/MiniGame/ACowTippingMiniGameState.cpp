ACowTippingMiniGameState::~ACowTippingMiniGameState()
{
	// The backing of the pick up HUD element was moved into m_oPortrait (see CreateLifeHuds)
	m_oPickUpHudElement.m_oBacking.RemoveSelf();

	// Disconnect the listener of the global animation event list
	AAnimationBreakpointUnitAction::Listener& rListener = As<AAnimationBreakpointUnitAction::Listener>( m_oAnimEventListener );

	if ( rListener.pNext != &rListener )
	{
		rListener.pPrev->pNext = rListener.pNext;
		rListener.pNext->pPrev = rListener.pPrev;
		rListener.pNext        = &rListener;
		rListener.pPrev        = &rListener;
	}

	rListener.pCaller   = TNULL;
	rListener.pCallback = TNULL;
}

