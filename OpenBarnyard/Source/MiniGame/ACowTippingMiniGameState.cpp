// Weighted list the kid characters are picked from (built on the stack by CreateKids, picked by PickWeighted)
struct CowTippingKidPicker
{
	struct Entry
	{
		TINT iValue;
		TINT iWeight;
	};

	void Remove( Entry* a_pEntry );

	TRandom*                   pRandom;
	TINT                       iTotalWeight;
	Toshi::T2Vector<Entry, 13> vecEntries;
};

// T2Vector<CowTippingKidPicker::Entry, 13>::Erase (retail clears the slot that's freed at the end)
// $Barnyard: FUNCTION 004ab170
static void EraseKidPickerEntry( Toshi::T2Vector<CowTippingKidPicker::Entry, 13>& a_rVector, TINT a_iIndex )
{
	a_rVector.Erase( a_rVector.Begin() + a_iIndex );
}

// $Barnyard: FUNCTION 004ad350
void CowTippingKidPicker::Remove( Entry* a_pEntry )
{
	for ( auto it = vecEntries.Begin(); it != vecEntries.End(); it++ )
	{
		if ( a_pEntry == &( *it ) )
		{
			iTotalWeight -= a_pEntry->iWeight;
			EraseKidPickerEntry( vecEntries, it.Index() );
			return;
		}
	}
}

